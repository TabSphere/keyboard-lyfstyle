// Builds the website's data from the app's own catalogue, so the site always matches the app.
// Run: node scripts/build-site-data.mjs  →  site/assets/data.js + site/assets/themes/*
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalogue = JSON.parse(fs.readFileSync(path.join(root, 'shared/styles.json'), 'utf8'));
const out = path.join(root, 'site/assets');
const themeDir = path.join(out, 'themes');
fs.mkdirSync(path.join(themeDir, 'thumbs'), { recursive: true });

// The site is a teaser: it only ships the few styles it shows, not the whole catalogue.
const SITE_STYLES = ['frame-sparkles', 'script', 'sans-bold', 'bold-script', 'fraktur', 'circled', 'mythic', 'frame-hearts'];
const totalStyles = catalogue.styles.filter((s) => s.kind !== 'normal').length;
const styles = catalogue.styles
  .filter((s) => SITE_STYLES.includes(s.id))
  .map((s) => {
    const item = { id: s.id, name: s.name, group: s.group, kb: s.keyboard !== false && s.kind !== 'composite', free: !s.isPro, map: s.mapping };
    if (s.prefix) item.pre = s.prefix;
    if (s.suffix) item.suf = s.suffix;
    if (s.joiner) item.join = s.joiner;
    return item;
  });

const themes = catalogue.themes.map((t) => {
  const item = { id: t.id, name: t.name, group: t.group, bg: t.background, key: t.key, text: t.text, accent: t.accent, dark: t.dark, free: !t.isPro };
  if (t.image) {
    item.img = t.image;
    item.alpha = t.keyAlpha ?? 1;
    for (const [from, to] of [[`assets/keyboard-themes/${t.image}`, `themes/${t.image}`], [`assets/keyboard-themes/thumbs/${t.image}`, `themes/thumbs/${t.image}`]]) {
      const src = path.join(root, from);
      if (fs.existsSync(src)) fs.copyFileSync(src, path.join(out, to));
    }
  }
  return item;
});

const data = `// Generated by scripts/build-site-data.mjs from shared/styles.json. Do not edit by hand.\nwindow.LYF = ${JSON.stringify({ totalStyles, styles, themes })};\n`;
fs.writeFileSync(path.join(out, 'data.js'), data);
console.log(`styles ${styles.length} of ${totalStyles}, themes ${themes.length} (${themes.filter((t) => t.img).length} pictures), data.js ${(data.length / 1024).toFixed(0)} KB`);
